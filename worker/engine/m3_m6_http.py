UA = {"User-Agent": brand.USER_AGENT,
      "Accept": "text/html,application/xhtml+xml,*/*;q=0.8",
      "Accept-Language": "es,en;q=0.8"}
MAX_REQUESTS = 25
MAX_BYTES = 2 * 1024 * 1024
DENIED = (403, 406, 429, 503)


class Budget(Exception):
    pass


class SiteClient:
    """Cliente HTTP con los limites de la especificacion (seccion 7).

    Valida cada destino contra redes internas (anti-SSRF), sigue como mucho
    5 redirecciones y solo dentro del mismo dominio registrable, y lleva la
    cuenta de peticiones y bytes descargados.
    """

    def __init__(self, domain: str):
        self.domain = domain
        self.requests = 0
        self.bytes = 0
        self.c = httpx.AsyncClient(timeout=10, headers=UA, verify=True,
                                   limits=httpx.Limits(max_connections=4))

    async def close(self):
        await self.c.aclose()

    async def get(self, url: str, max_read: int | None = None) -> httpx.Response:
        for _ in range(6):
            if self.requests >= MAX_REQUESTS or self.bytes >= MAX_BYTES:
                raise Budget("presupuesto de peticiones agotado")
            await validar_url_async(url)
            self.requests += 1
            headers = {"Range": f"bytes=0-{max_read - 1}"} if max_read else None
            r = await self.c.get(url, headers=headers, follow_redirects=False)
            self.bytes += len(r.content)
            if r.status_code not in REDIRECCIONES or not r.headers.get("location"):
                return r
            nxt = str(r.url.join(r.headers["location"]))
            host = httpx.URL(nxt).host
            if registrable(host) != registrable(self.domain):
                return r                    # no salimos del dominio analizado
            url = nxt
        return r


# --------------------------------------------------------------- firewall
WAF_HEADERS = {           # cabeceras que delatan un firewall/CDN delante
    "cf-ray": "cloudflare", "x-sucuri-id": "sucuri", "x-sucuri-cache": "sucuri",
    "x-iinfo": "imperva", "x-cdn": "imperva", "x-amzn-waf-action": "aws-waf",
    "x-akamai-transformed": "akamai", "akamai-grn": "akamai",
}
WAF_COOKIES = {"incap_ses": "imperva", "visid_incap": "imperva",
               "bigipserver": "f5-big-ip", "__cf_bm": "cloudflare",
               "sucuri_cloudproxy": "sucuri"}
WAF_SERVER = {"cloudflare": "cloudflare", "sucuri": "sucuri",
              "akamaighost": "akamai", "imunify360": "imunify360",
              "mod_security": "modsecurity", "awselb": None}
BLOCK_PAGES = {            # firmas de paginas de bloqueo o desafio
    "imunify360": ("wsidchk", "your request is being verified", "imunify360",
                   "z0f76a1d14fd21a8fb5fd0d03e0fdc3d3cedae52f"),
    "cloudflare": ("checking your browser", "cf-challenge", "attention required! | cloudflare",
                   "cf-browser-verification", "just a moment..."),
    "sucuri": ("sucuri website firewall", "access denied - sucuri"),
    "wordfence": ("generated by wordfence", "wordfence-blocked"),
    "modsecurity": ("mod_security", "modsecurity", "not acceptable!"),
    "imperva": ("incapsula incident id", "_incapsula_resource"),
    "generic": ("verifying you are human", "ddos protection by", "enable javascript and cookies to continue"),
}


def waf_signature(r: httpx.Response) -> str | None:
    """Producto si la respuesta delata un firewall, por cabeceras o cookies."""
    h = {k.lower(): v.lower() for k, v in r.headers.items()}
    if "cf-mitigated" in h:
        return "cloudflare"
    for k, prod in WAF_HEADERS.items():
        if k in h:
            return prod
    server = h.get("server", "")
    for k, prod in WAF_SERVER.items():
        if k in server and prod:
            return prod
    cookies = " ".join(r.headers.get_list("set-cookie")).lower()
    for k, prod in WAF_COOKIES.items():
        if k in cookies:
            return prod
    return None


def block_page(r: httpx.Response) -> str | None:
    body = r.text[:12000].lower()
    for prod, sigs in BLOCK_PAGES.items():
        if any(s in body for s in sigs):
            return prod
    return None


def is_blocked(r: httpx.Response) -> str | None:
    """Producto que bloqueo, o None. Exige firma o desafio, nunca un 403 solo."""
    page = block_page(r)
    if page and page != "generic":
        return page               # pagina de bloqueo conocida (puede venir con 200)
    if page == "generic" and (r.status_code in DENIED or len(r.text) < 20000):
        # "verifying you are human" en una pagina corta: es un desafio.
        return waf_signature(r) or "desconocido"
    if r.status_code in DENIED:
        sig = waf_signature(r)
        if sig:
            return sig
    return None


# ------------------------------------------------------- M3 cabeceras
SESSION_COOKIE = re.compile(r"(sess|sid|token|auth|login|wordpress_logged|wp-settings|laravel_session|ci_session|jsession)", re.I)
MIXED = re.compile(r"<(?:script|img|link|iframe|source|video|audio)\b[^>]+(?:src|href)\s*=\s*[\"']http://", re.I)


def headers_layer(home: httpx.Response, http_final: httpx.Response | None) -> ModuleResult:
    m = ModuleResult("L3")
    h = {k.lower(): v for k, v in home.headers.items()}
    final_https = str(home.url).startswith("https://")

    if http_final is not None and not str(http_final.url).startswith("https://") \
            and http_final.status_code not in REDIRECCIONES:
        m.findings.append(finding("F-HDR-001", "medio", {"final_url": str(http_final.url)}))
    elif http_final is not None and http_final.status_code in REDIRECCIONES:
        loc = http_final.headers.get("location", "")
        if not loc.startswith("https://"):
            m.findings.append(finding("F-HDR-001", "medio", {"location": loc[:120]}))

    hsts = h.get("strict-transport-security", "")
    if not hsts:
        m.findings.append(finding("F-HDR-002", "medio", {"header": "Strict-Transport-Security"}))
    else:
        mx = re.search(r"max-age=(\d+)", hsts)
        days = int(mx.group(1)) // 86400 if mx else 0
        if days >= 180:
            m.positives.append(positive("P-HDR-001", n=days))
        else:
            m.findings.append(finding("F-HDR-002", "medio", {"max_age_days": days}))

    csp = h.get("content-security-policy", "")
    if not csp:
        m.findings.append(finding("F-HDR-003", "medio", {"header": "Content-Security-Policy"}))
    if final_https and MIXED.search(home.text[:300000]):
        m.findings.append(finding("F-HDR-004", "medio", {"page": str(home.url)}))
    if "x-frame-options" not in h and "frame-ancestors" not in csp:
        m.findings.append(finding("F-HDR-005", "bajo", {"header": "X-Frame-Options"}))

    weak = []
    for raw in home.headers.get_list("set-cookie"):
        name = raw.split("=", 1)[0].strip()
        low = raw.lower()
        if SESSION_COOKIE.search(name) and not all(
                a in low for a in ("secure", "httponly", "samesite")):
            weak.append(name)
    if weak:
        m.findings.append(finding("F-HDR-006", "bajo", {"cookies": weak[:5]}))
    if "x-content-type-options" not in h:
        m.findings.append(finding("F-HDR-007", "bajo", {"header": "X-Content-Type-Options"}))
    if "referrer-policy" not in h or "permissions-policy" not in h:
        m.findings.append(finding("F-HDR-008", "observ", {}))

    faltan = len([f for f in m.findings if f["severity"] != "observ"])
    m.note = f"{faltan} cabeceras o ajustes por mejorar" if faltan else "Cabeceras recomendadas presentes"
    return m.finish()


# ------------------------------------------------ M4 archivos sensibles
def _not_html(r: httpx.Response) -> bool:
    ct = r.headers.get("content-type", "").lower()
    head = r.content[:200].lstrip().lower()
    return "text/html" not in ct and not head.startswith((b"<!doctype", b"<html"))


def _txt(r):  # solo para comparar firmas; nunca se guarda
    return r.content[:4096].decode("utf-8", "replace")


PATHS = [  # (ruta, hallazgo, firma)
    ("/.env", "F-FILE-001", lambda r: _not_html(r) and re.search(r"^[A-Z][A-Z0-9_]{2,}=", _txt(r), re.M)),
    ("/.git/HEAD", "F-FILE-002", lambda r: _txt(r).startswith("ref: ")),
    ("/.git/config", "F-FILE-002", lambda r: "[core]" in _txt(r)),
    ("/.svn/entries", "F-FILE-002", lambda r: _not_html(r) and (_txt(r).strip()[:2].isdigit() or "svn:" in _txt(r))),
    ("/.DS_Store", "F-FILE-005", lambda r: r.content[:8] == b"\x00\x00\x00\x01Bud1"),
    ("/backup.zip", "F-FILE-003", lambda r: r.content[:4] == b"PK\x03\x04"),
    ("/backup.sql", "F-FILE-003", lambda r: _not_html(r) and re.search(r"(CREATE TABLE|INSERT INTO|-- MySQL dump)", _txt(r), re.I)),
    ("/db.sql", "F-FILE-003", lambda r: _not_html(r) and re.search(r"(CREATE TABLE|INSERT INTO|-- MySQL dump)", _txt(r), re.I)),
    ("/dump.sql", "F-FILE-003", lambda r: _not_html(r) and re.search(r"(CREATE TABLE|INSERT INTO|-- MySQL dump)", _txt(r), re.I)),
    ("/database.sql", "F-FILE-003", lambda r: _not_html(r) and re.search(r"(CREATE TABLE|INSERT INTO|-- MySQL dump)", _txt(r), re.I)),
    ("/wp-config.php.bak", "F-FILE-003", lambda r: "DB_" in _txt(r) and "define" in _txt(r)),
    ("/wp-config.php~", "F-FILE-003", lambda r: "DB_" in _txt(r) and "define" in _txt(r)),
    ("/config.php.bak", "F-FILE-003", lambda r: _not_html(r) and "<?php" in _txt(r)),
    ("/phpinfo.php", "F-FILE-004", lambda r: "phpinfo()" in _txt(r) or "PHP Version" in _txt(r)),
    ("/info.php", "F-FILE-004", lambda r: "phpinfo()" in _txt(r) or "PHP Version" in _txt(r)),
    ("/server-status", "F-FILE-004", lambda r: "Apache Server Status" in _txt(r)),
    ("/phpmyadmin/", "F-FILE-006", lambda r: "phpmyadmin" in _txt(r).lower() and "pma_" in _txt(r).lower()),
    ("/.htpasswd", "F-FILE-003", lambda r: _not_html(r) and re.search(r"^[^:\s]+:(\$apr1\$|\$2[aby]\$|\{SHA\})", _txt(r), re.M)),
    ("/.well-known/security.txt", "SECTXT", lambda r: "contact:" in _txt(r).lower()),
    ("/wp-content/uploads/", "F-FILE-005", lambda r: "index of /" in _txt(r).lower()),
]
SEV_FILE = {"F-FILE-001": "alto", "F-FILE-002": "alto", "F-FILE-003": "alto",
            "F-FILE-004": "medio", "F-FILE-005": "medio", "F-FILE-006": "medio"}


async def files_layer(cli: SiteClient, base: str, soft404: bool) -> ModuleResult:
    m = ModuleResult("L4")
    hits: dict[str, list] = {}
    sectxt = False
    checked = 0
    for path, fid, sig in PATHS:
        try:
            r = await cli.get(base + path, max_read=4096)
        except Budget:
            break
        except Exception:
            await asyncio.sleep(1)
            continue
        checked += 1
        ok = r.status_code in (200, 206)
        matched = bool(ok and sig(r))
        # Con 404 blando la firma de contenido es lo unico que vale: el
        # codigo 200 por si solo no prueba nada.
        if matched and fid == "SECTXT":
            sectxt = True
        elif matched:
            hits.setdefault(fid, []).append({"path": path, "status": r.status_code,
                                             "size": len(r.content), "matched": True})
        await asyncio.sleep(1)              # 1 peticion por segundo
    if checked == 0:
        return m.undetermined("http_error")
    for fid, ev in hits.items():
        m.findings.append(finding(fid, SEV_FILE[fid], {"paths": [e["path"] for e in ev]}))
    if not sectxt:
        m.findings.append(finding("F-FILE-007", "observ", {}))
    if not hits:
        m.positives.append(positive("P-FILE-001", n=checked))
    m.note = (f"{len(hits)} tipos de archivo expuestos" if hits
              else f"Sin archivos sensibles en {checked} rutas comunes")
    m.evidence = {"checked": checked, "soft404": soft404}
    return m.finish()


# ------------------------------------------------------ M5 CMS
GEN_RE = re.compile(r'<meta[^>]+name=["\']generator["\'][^>]+content=["\']([^"\']+)', re.I)
PLUGIN_VER_RE = re.compile(r"/wp-content/plugins/([a-z0-9\-_]+)/[^\"'\s]+?\?ver=([0-9][0-9.]*)", re.I)
PLUGIN_RE = re.compile(r"/wp-content/plugins/([a-z0-9\-_]+)/", re.I)


async def _plugin_info(slug: str) -> dict | None:
    """Ultima version y fecha de actualizacion en wordpress.org (no es el sitio)."""
    url = ("https://api.wordpress.org/plugins/info/1.2/?action=plugin_information"
           f"&request[slug]={slug}&request[fields][sections]=0")
    try:
        async with httpx.AsyncClient(timeout=8) as c:
            r = await c.get(url)
            if r.status_code != 200:
                return None
            j = r.json()
            if not isinstance(j, dict) or "version" not in j:
                return None
            return {"version": j.get("version"), "updated": j.get("last_updated", "")}
    except Exception:
        return None


def _vt(v: str) -> tuple:
    return tuple(int(x) for x in re.findall(r"\d+", v)[:4])


async def cms_layer(cli: SiteClient, base: str, home: httpx.Response) -> ModuleResult:
    m = ModuleResult("L5")
    html = home.text[:400000]
    gen = GEN_RE.search(html)
    generator = gen.group(1).strip() if gen else ""
    is_wp = "/wp-content/" in html or "/wp-includes/" in html or "wordpress" in generator.lower()
    cms = None
    version = None
    if is_wp:
        cms = "WordPress"
        mv = re.search(r"WordPress\s+([0-9.]+)", generator)
        version = mv.group(1) if mv else None
    elif "joomla" in generator.lower():
        cms = "Joomla"
        mv = re.search(r"([0-9]+\.[0-9.]+)", generator)
        version = mv.group(1) if mv else None
    elif "drupal" in generator.lower() or "drupal-settings-json" in html:
        cms = "Drupal"
        mv = re.search(r"Drupal\s+([0-9.]+)", generator)
        version = mv.group(1) if mv else None
    elif any(s in html for s in ("cdn.shopify.com", "static.wixstatic.com", "squarespace.com")):
        cms = "plataforma gestionada"

    m.evidence = {"cms": cms, "version": version}
    if not cms:
        m.note = "No se detectó un gestor de contenidos conocido"
        return m.finish()
    if cms == "plataforma gestionada":
        m.note = "Sitio en una plataforma gestionada (Shopify, Wix o similar): el proveedor la actualiza"
        return m.finish()

    if version:
        m.findings.append(finding("F-CMS-001", "observ", {"version": version}))
    if cms == "WordPress" and version:
        ultima = await latest_version()
        if ultima:
            v = comparar(version, ultima)
            if v["estado"] in ("parche_pendiente", "rama_atrasada"):
                sev = "alto" if v["estado"] == "rama_atrasada" and v["ramas_detras"] >= 2 else "medio"
                m.findings.append(finding("F-CMS-002", sev, {"version": version, "latest": ultima},
                                          cms=cms, version=version))

    if cms == "WordPress":
        plugins = {s: v for s, v in PLUGIN_VER_RE.findall(html) if v != version}
        for s in set(PLUGIN_RE.findall(html)):
            plugins.setdefault(s, None)
        slugs = sorted(plugins)[:12]
        infos = await asyncio.gather(*[_plugin_info(s) for s in slugs])
        outdated, abandoned = [], []
        for slug, info in zip(slugs, infos):
            if not info:
                continue
            seen = plugins.get(slug)
            if seen and info["version"] and _vt(seen) < _vt(info["version"]):
                outdated.append(slug)
            try:
                upd = datetime.strptime(info["updated"][:10], "%Y-%m-%d").date()
                if (date.today() - upd).days > 730:
                    abandoned.append(slug)
            except ValueError:
                pass
        if outdated:
            m.findings.append(finding("F-CMS-003", "medio", {"plugins": outdated[:8]}, n=len(outdated)))
        if abandoned:
            m.findings.append(finding("F-CMS-004", "medio", {"plugins": abandoned[:8]}, n=len(abandoned)))
        try:
            ru = await cli.get(base + "/wp-json/wp/v2/users")
            if ru.status_code == 200 and ru.text.lstrip().startswith("["):
                users = [u.get("slug") for u in ru.json() if isinstance(u, dict)][:5]
                if users:
                    m.findings.append(finding("F-CMS-005", "medio", {"users": len(users)}))
        except Exception:
            pass
        m.evidence["plugins"] = len(plugins)
    m.note = f"{cms}{' ' + version if version else ''}"
    return m.finish()


# ------------------------------------------------------ M6 servidor
PHP_EOL = {"5.6": date(2018, 12, 31), "7.0": date(2019, 1, 10), "7.1": date(2019, 12, 1),
           "7.2": date(2020, 11, 30), "7.3": date(2021, 12, 6), "7.4": date(2022, 11, 28),
           "8.0": date(2023, 11, 26), "8.1": date(2025, 12, 31), "8.2": date(2026, 12, 31),
           "8.3": date(2027, 12, 31), "8.4": date(2028, 12, 31), "8.5": date(2029, 12, 31)}
# Ramas sin soporte conocidas (sin consultar red). nginx: ramas antiguas;
# Apache: todo lo anterior a 2.4.
SERVER_EOL = [("apache", re.compile(r"apache/(2\.[0-2])\.\d+", re.I), date(2018, 1, 1)),
              ("nginx", re.compile(r"nginx/(1\.(?:[0-9]|1[0-9]|2[0-3]))\.\d+", re.I), date(2023, 4, 11))]


def server_layer(home: httpx.Response, waf: str | None) -> ModuleResult:
    m = ModuleResult("L6")
    h = {k.lower(): v for k, v in home.headers.items()}
    blob = " ".join(h.get(k, "") for k in ("server", "x-powered-by"))
    today = date.today()

    mp = re.search(r"PHP/(\d+\.\d+)(?:\.\d+)?", blob, re.I)
    if mp and mp.group(1) in PHP_EOL and today > PHP_EOL[mp.group(1)]:
        eol = PHP_EOL[mp.group(1)]
        sev = "alto" if (today - eol).days > 365 else "medio"
        m.findings.append(finding("F-SRV-001", sev, {"version": mp.group(0), "eol": eol.isoformat()},
                                  software="PHP", version=mp.group(0).split("/", 1)[1]))
    for name, rx, eol in SERVER_EOL:
        ms = rx.search(blob)
        if ms:
            sev = "alto" if (today - eol).days > 365 else "medio"
            m.findings.append(finding("F-SRV-001", sev, {"server": ms.group(0)},
                                      software=name.capitalize(), version=ms.group(0).split("/", 1)[1]))
    for k in ("server", "x-powered-by", "x-aspnet-version"):
        if k in h and re.search(r"\d", h[k]):
            m.findings.append(finding("F-SRV-002", "bajo", {"header": k, "value": h[k][:60]}))
            break
    if waf:
        m.positives.append(positive("P-WAF-001", producto=waf))
    else:
        m.findings.append(finding("F-SRV-003", "observ", {}))
    srv = h.get("server", "")
    m.note = (f"Servidor: {srv[:40]}" if srv else "El servidor no revela su software") + \
             (f" · firewall: {waf}" if waf else "")
    m.evidence = {"server": srv[:60], "waf": waf}
    return m.finish()


# -------------------------------------------------------------- orquesta
async def run(domain: str, host: str) -> dict:
    """Devuelve {'layers': {L3..L6: ModuleResult}, 'waf': {...}}."""
    cli = SiteClient(domain)
    base = f"https://{host}"
    out_waf = {"detected": False, "product": None}
    try:
        try:
            home = await cli.get(base + "/")
        except (httpx.ConnectError, httpx.ConnectTimeout, httpx.ReadTimeout, httpx.TimeoutException) as e:
            reason = "timeout" if "imeout" in type(e).__name__ else "http_error"
            return {"layers": {L: ModuleResult(L).undetermined(reason) for L in ("L3", "L4", "L5", "L6")},
                    "waf": out_waf, "blocked": False}
        except Budget:
            return {"layers": {L: ModuleResult(L).undetermined("http_error") for L in ("L3", "L4", "L5", "L6")},
                    "waf": out_waf, "blocked": False}

        blocked_by = is_blocked(home)
        if blocked_by:
            # Un unico reintento tras 5 s, con la misma identidad.
            await asyncio.sleep(5)
            try:
                home = await cli.get(base + "/")
                blocked_by = is_blocked(home)
            except Exception:
                pass
        if blocked_by:
            print(f"[engine] {domain} bloqueado por {blocked_by} (HTTP {home.status_code})", flush=True)
            out_waf = {"detected": True, "product": blocked_by}
            layers = {L: ModuleResult(L).undetermined("waf_blocked") for L in ("L3", "L4", "L5", "L6")}
            layers["L6"].positives.append(positive("P-WAF-001", producto=blocked_by))
            return {"layers": layers, "waf": out_waf, "blocked": True}

        if home.status_code >= 400:
            return {"layers": {L: ModuleResult(L).undetermined("http_error") for L in ("L3", "L4", "L5", "L6")},
                    "waf": out_waf, "blocked": False}

        waf = waf_signature(home)
        out_waf = {"detected": bool(waf), "product": waf}

        # 404 blando: si una ruta imposible devuelve 200, las firmas de
        # contenido son lo unico que cuenta en M4.
        soft404 = False
        try:
            probe = await cli.get(f"{base}/{brand.PROBE_PREFIX}-{uuid.uuid4().hex[:12]}", max_read=4096)
            soft404 = probe.status_code == 200
            if is_blocked(probe) and not waf:
                waf = is_blocked(probe)
                out_waf = {"detected": True, "product": waf}
        except Exception:
            pass
        try:
            http_final = await cli.get(f"http://{host}/", max_read=4096)
        except Exception:
            http_final = None

        l3 = headers_layer(home, http_final)
        l6 = server_layer(home, waf)
        l5 = await cms_layer(cli, base, home)
        l4 = await files_layer(cli, base, soft404)
        return {"layers": {"L3": l3, "L4": l4, "L5": l5, "L6": l6}, "waf": out_waf, "blocked": False}
    finally:
        await cli.close()
