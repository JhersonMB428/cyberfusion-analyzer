"""M3 a M6 · Cabeceras, archivos sensibles, gestor de contenidos y servidor.

Comparten una sola peticion a la portada y un presupuesto de peticiones al
sitio analizado (maximo 25 por analisis, 1 por segundo en M4). Si un
firewall bloquea, se registra y se respeta: un unico reintento con la misma
identidad y nada de rotar IP, user-agent ni proxies (principio 2).
"""
from __future__ import annotations

import asyncio
import re
import uuid
from datetime import date, datetime, timezone

import httpx

from .. import brand
